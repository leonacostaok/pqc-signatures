#!/usr/bin/env python3
"""Render preliminary result tables below <!-- RESULTS --> in docs/liboqs/{verify-stages,memory,validation}.md."""
import json
import math
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
DOCS = ROOT / "docs/liboqs"
RES = ROOT / "results/liboqs"
MARK = "<!-- RESULTS -->"


def t(ns):
    return "—" if ns is None else (f"{ns/1e9:.2f} s" if ns >= 1e9 else f"{ns/1e6:.2f} ms" if ns >= 1e6 else f"{ns/1e3:.1f} µs")


def geo(a):
    return math.exp(sum(map(math.log, a)) / len(a)) if a else None


def kb(b):
    return "—" if b is None else f"{b/1024:.1f} KiB" if b >= 1024 else f"{b} B"


def replace_results(path, md):
    head = path.read_text().split(MARK)[0].rstrip()
    path.write_text(head + "\n\n" + MARK + "\n\n" + md)


def stages():
    f = RES / "stages.jsonl"
    if not f.exists():
        return
    rows = [json.loads(l) for l in f.read_text().splitlines() if l.strip()]
    md = "## Results (PRELIMINARY dev run, small budget, shared machine; regenerated by the orchestrator)\n\n"
    stage_order = ["decode", "mu", "expandA", "w_approx", "hint_check", "hmsg", "fors", "ht_wots", "ht_auth", "total", "total_best"]
    params = []
    for r in rows:
        if r["param"] not in params:
            params.append(r["param"])
    md += "### Stage share of the v0 pipeline (median wall per stage)\n\n| param | " + " | ".join(s for s in stage_order if s not in ("total", "total_best")) + " | total | total_best |\n|---|" + "---|" * (len(stage_order)) + "\n"
    for p in params:
        cells = []
        for s in stage_order:
            v = "total_best" if s == "total_best" else ("total" if s == "total" else f"{s}.v0")
            r = next((x for x in rows if x["param"] == p and x["variant"] == v and x["stage"] == s), None)
            cells.append(t(r["wall_ns_median"]) if r else "—")
        md += f"| {p} | " + " | ".join(cells) + " |\n"
    md += "\n### Stage variants (speedup = throughput vs the stage's v0, geometric mean over params; match = canonical output equals v0)\n\n"
    for s in stage_order:
        if s in ("total", "total_best"):
            continue
        vs = sorted({r["variant"] for r in rows if r["stage"] == s})
        if not vs:
            continue
        md += f"#### {s}\n\n| variant | name | geomean speedup | per param (median) | all match |\n|---|---|---|---|---|\n"
        for v in vs:
            sp, cells, ok = [], [], True
            for p in params:
                r = next((x for x in rows if x["param"] == p and x["variant"] == v and x["stage"] == s), None)
                b = next((x for x in rows if x["param"] == p and x["variant"] == f"{s}.v0" and x["stage"] == s), None)
                if not r:
                    continue
                ok = ok and r["match"]
                if b:
                    sp.append(r["ops_per_sec"] / b["ops_per_sec"])
                cells.append(f"{p.replace('SLH-DSA-', '')} {t(r['wall_ns_median'])}")
            n = next(x for x in rows if x["variant"] == v)
            md += f"| `{v}` | {n['variant_name']} | {geo(sp):.2f}× | {', '.join(cells)} | {'yes' if ok else '**NO**'} |\n"
        md += "\n"
    replace_results(DOCS / "verify-stages.md", md)


def memory():
    f = RES / "memory.jsonl"
    if not f.exists():
        return
    rows = [json.loads(l) for l in f.read_text().splitlines() if l.strip()]
    md = "## Results (PRELIMINARY dev run)\n\n"
    for op in ["keygen", "sign", "verify", "verify-stage"]:
        sub = [r for r in rows if r["op"] == op]
        if not sub:
            continue
        vs = []
        for r in sub:
            if r["variant"] not in vs:
                vs.append(r["variant"])
        params = []
        for r in sub:
            if r["param"] not in params:
                params.append(r["param"])
        md += f"### {op}: peak stack per op (heap alloc / peak in parentheses when non-zero)\n\n| variant | " + " | ".join(p.replace("SLH-DSA-", "") for p in params) + " |\n|---|" + "---|" * len(params) + "\n"
        for v in vs:
            cells = []
            for p in params:
                r = next((x for x in sub if x["variant"] == v and x["param"] == p), None)
                if not r:
                    cells.append("—")
                    continue
                c = kb(r["stack_bytes"])
                if r["heap_alloc_bytes_per_op"]:
                    c += f" ({r['heap_alloc_bytes_per_op']}/{r['heap_peak_bytes']})"
                if not r["match"]:
                    c += " ✗"
                cells.append(c)
            label = f"`{v}`" + (f" {r['stage']}" if op == "verify-stage" and r and r.get("stage") and r["stage"] != v.split('.')[0] else "")
            md += f"| {label} | " + " | ".join(cells) + " |\n"
        md += "\n"
    replace_results(DOCS / "memory.md", md)


def validation():
    f = RES / "validation.json"
    if not f.exists():
        return
    d = json.loads(f.read_text())
    md = "## Results\n\n| variant | pass | fail | skipped |\n|---|---|---|---|\n"
    for v, s in d["summary"].items():
        md += f"| `{v}` | {s['pass']} | {s['fail']} | {s['skipped']} |\n"
    fails = [r for r in d["results"] if r["pass"] is False]
    md += f"\nTotal: {len(d['results'])} results, {len(fails)} failures.\n"
    if fails:
        md += "\n| id | variant | got | error |\n|---|---|---|---|\n"
        for r in fails[:50]:
            md += f"| {r['id']} | {r['variant']} | {r['got']} | {r['error']} |\n"
    replace_results(DOCS / "validation.md", md)


if __name__ == "__main__":
    for what in (sys.argv[1:] or ["stages", "memory", "validation"]):
        {"stages": stages, "memory": memory, "validation": validation}[what]()
    print("rendered")

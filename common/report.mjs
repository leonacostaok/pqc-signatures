// Turns results/<lib>/bench.jsonl into per-process tables (docs/<lib>/<op>.md after <!-- RESULTS -->)
// and the cross-library summary RESULTS.md. Speedups compare throughput (ops/s) vs the op's v0 baseline,
// so parallel batch variants are credited for throughput while CPU/op shows what they cost.
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const LIBS = ['noble', 'liboqs', 'openssl', 'circl', 'rustcrypto', 'bouncycastle'];
const OPS = ['keygen', 'sign', 'verify'];
const PARAMS = JSON.parse(readFileSync(new URL('common/vectors.json', root))).params.map((p) => p.name);

const t = (ns) => ns == null ? '—' : ns >= 1e9 ? `${(ns / 1e9).toFixed(2)} s` : ns >= 1e6 ? `${(ns / 1e6).toFixed(2)} ms` : `${(ns / 1e3).toFixed(1)} µs`;
const x = (v) => v == null || !isFinite(v) ? '—' : `${v.toFixed(2)}×`;
const geo = (a) => a.length ? Math.exp(a.reduce((s, v) => s + Math.log(v), 0) / a.length) : null;
const eff = (r) => 1e9 / r.ops_per_sec; // effective ns per op (throughput based)

const data = {};
for (const l of LIBS) {
  const f = new URL(`results/${l}/bench.jsonl`, root);
  if (!existsSync(f)) continue;
  data[l] = readFileSync(f, 'utf8').trim().split('\n').filter(Boolean).map((s) => JSON.parse(s));
}
const get = (l, op, p, v) => data[l]?.find((r) => r.op === op && r.param === p && r.variant === v);
const variants = (l, op) => [...new Set(data[l].filter((r) => r.op === op).map((r) => r.variant))].sort();

// per-lib per-op docs
for (const [l, rows] of Object.entries(data)) for (const op of OPS) {
  const f = new URL(`docs/${l}/${op}.md`, root);
  const head = existsSync(f) ? readFileSync(f, 'utf8').split('<!-- RESULTS -->')[0] : `# ${l}: ${op}\n\n`;
  const vs = variants(l, op);
  let md = '<!-- RESULTS -->\n\n## Results\n\n';
  const meta = rows.find((r) => r.op === op);
  if (!meta) continue;
  md += `Generated by \`common/report.mjs\` from \`results/${l}/bench.jsonl\` (${meta.lib} ${meta.lib_version}, ${meta.runtime}). Speedup = throughput vs \`${op}.v0\`.\n\n`;
  md += '### Summary (geometric mean speedup over all params)\n\n| variant | name | geomean speedup | geomean CPU/op vs v0 | all outputs match |\n|---|---|---|---|---|\n';
  for (const v of vs) {
    const sp = [], cp = []; let ok = true;
    for (const p of PARAMS) { const r = get(l, op, p, v), b = get(l, op, p, `${op}.v0`); if (!r) continue; ok &&= r.match === true; if (b) { sp.push(r.ops_per_sec / b.ops_per_sec); cp.push(r.cpu_ns_per_op / b.cpu_ns_per_op); } }
    const n = rows.find((r) => r.variant === v);
    md += `| \`${v}\` | ${n.variant_name} | ${x(geo(sp))} | ${x(geo(cp))} | ${ok ? 'yes' : '**NO**'} |\n`;
  }
  md += '\n### Per parameter set\n\n';
  for (const p of PARAMS) {
    const b = get(l, op, p, `${op}.v0`); if (!b) continue;
    md += `#### ${p}\n\n| variant | median | p95 | CPU/op | CPU util | threads | ops/s | speedup | match |\n|---|---|---|---|---|---|---|---|---|\n`;
    for (const v of vs) { const r = get(l, op, p, v); if (!r) continue;
      md += `| \`${v}\` ${r.variant_name} | ${t(r.wall_ns_median)} | ${t(r.wall_ns_p95)} | ${t(r.cpu_ns_per_op)} | ${r.cpu_util.toFixed(2)} | ${r.threads} | ${r.ops_per_sec.toFixed(r.ops_per_sec < 10 ? 2 : 0)} | ${x(r.ops_per_sec / b.ops_per_sec)} | ${r.match ? '✓' : '✗'} |\n`; }
    md += '\n';
  }
  writeFileSync(f, head.trimEnd() + '\n\n' + md);
}

// cross-library summary
const libs = Object.keys(data);
let md = '# Results: PQC signatures across 6 libraries\n\nAll numbers from one quiet, sequential run on the same 4-core x86-64 VM (see `common/run-all.sh`). ';
md += 'Each process (keygen, sign, verify) is measured separately: median wall time per op from individual timings, CPU time per op from process user+sys time. ';
md += '"best" = highest throughput among the 6 variants of that process; single-threaded best excludes parallel batch variants. Every number here comes from a run whose output byte-matched the reference (see `results/MATCH.md`).\n\n';
for (const op of OPS) {
  md += `## ${op}\n\n### Baseline (v0) median time per op\n\n| param | ${libs.join(' | ')} |\n|---|${libs.map(() => '---').join('|')}|\n`;
  for (const p of PARAMS) { if (!libs.some((l) => get(l, op, p, `${op}.v0`))) continue;
    const vals = libs.map((l) => get(l, op, p, `${op}.v0`)?.wall_ns_median);
    const min = Math.min(...vals.filter((v) => v != null));
    md += `| ${p} | ${vals.map((v) => v == null ? '—' : v === min ? `**${t(v)}**` : t(v)).join(' | ')} |\n`; }
  md += `\n### Best single-threaded variant: effective time per op (speedup vs own v0, variant)\n\n| param | ${libs.join(' | ')} |\n|---|${libs.map(() => '---').join('|')}|\n`;
  for (const p of PARAMS) { if (!libs.some((l) => get(l, op, p, `${op}.v0`))) continue;
    md += `| ${p} | ${libs.map((l) => { const rs = (data[l] ?? []).filter((r) => r.op === op && r.param === p && r.threads === 1 && r.match); if (!rs.length) return '—';
      const best = rs.reduce((a, b) => (b.ops_per_sec > a.ops_per_sec ? b : a)); const b = get(l, op, p, `${op}.v0`);
      return `${t(eff(best))} (${x(best.ops_per_sec / b.ops_per_sec)}, ${best.variant.split('.')[1]})`; }).join(' | ')} |\n`; }
  md += `\n### Variant leaderboard (geomean speedup vs v0 across params)\n\n| lib | ${[1, 2, 3, 4, 5].map((i) => `v${i}`).join(' | ')} |\n|---|---|---|---|---|---|\n`;
  for (const l of libs) md += `| ${l} | ${[1, 2, 3, 4, 5].map((i) => { const v = `${op}.v${i}`; const sp = PARAMS.map((p) => { const r = get(l, op, p, v), b = get(l, op, p, `${op}.v0`); return r && b ? r.ops_per_sec / b.ops_per_sec : null; }).filter((s) => s != null);
      const n = data[l].find((r) => r.variant === v); return n ? `${n.variant_name}: ${x(geo(sp))}${n.threads > 1 ? ` (${n.threads} thr)` : ''}` : '—'; }).join(' | ')} |\n`;
  md += '\n';
}
writeFileSync(new URL('RESULTS.md', root), md);
writeFileSync(new URL('results/summary.json', root), JSON.stringify(Object.fromEntries(libs.map((l) => [l, data[l]])), null, 0));
console.log('wrote RESULTS.md and docs tables for', libs.join(', '));

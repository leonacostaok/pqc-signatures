// Phase 2 report: verify-stage split (results/<lib>/stages.jsonl) and stack/heap memory (results/<lib>/memory.jsonl).
// Writes tables into docs/<lib>/verify-stages.md and docs/<lib>/memory.md (after <!-- RESULTS -->)
// and appends cross-library sections to RESULTS.md.
import { readFileSync, writeFileSync, existsSync, appendFileSync } from 'node:fs';
const root = new URL('../', import.meta.url);
const LIBS = ['noble', 'liboqs', 'openssl', 'circl', 'rustcrypto', 'bouncycastle'];
const PARAMS = JSON.parse(readFileSync(new URL('common/vectors.json', root))).params.map((p) => p.name);
const STAGES = { 'ml-dsa': ['decode', 'mu', 'expandA', 'w_approx', 'hint_check'], 'slh-dsa': ['hmsg', 'fors', 'ht_wots', 'ht_auth'] };
const fam = (p) => (p.startsWith('ML-DSA') ? 'ml-dsa' : p.startsWith('SLH') ? 'slh-dsa' : 'falcon');
const t = (ns) => ns == null ? '—' : ns >= 1e9 ? `${(ns / 1e9).toFixed(2)} s` : ns >= 1e6 ? `${(ns / 1e6).toFixed(2)} ms` : `${(ns / 1e3).toFixed(1)} µs`;
const b = (n) => n == null ? '—' : n >= 1048576 ? `${(n / 1048576).toFixed(2)} MiB` : n >= 1024 ? `${(n / 1024).toFixed(1)} KiB` : `${n} B`;
const x = (v) => v == null || !isFinite(v) ? '—' : `${v.toFixed(2)}×`;
const load = (l, f) => { const u = new URL(`results/${l}/${f}`, root); return existsSync(u) ? readFileSync(u, 'utf8').trim().split('\n').filter(Boolean).map((s) => JSON.parse(s)) : null; };
const eff = (r) => r.ops_per_sec ? 1e9 / r.ops_per_sec : r.wall_ns_median; // throughput-based ns/op
const writeAfterMarker = (path, md, title) => {
  const f = new URL(path, root);
  const head = existsSync(f) ? readFileSync(f, 'utf8').split('<!-- RESULTS -->')[0] : `# ${title}\n\n`;
  writeFileSync(f, head.trimEnd() + '\n\n<!-- RESULTS -->\n\n' + md);
};

const S = {}, M = {}, B = {};
for (const l of LIBS) { const s = load(l, 'stages.jsonl'); if (s) S[l] = s; const m = load(l, 'memory.jsonl'); if (m) M[l] = m; const bb = load(l, 'bench.jsonl'); if (bb) B[l] = bb; }

// ---------- per-lib verify-stages docs
for (const [l, rows] of Object.entries(S)) {
  let md = `## Results\n\nGenerated by \`common/report-phase2.mjs\` from \`results/${l}/stages.jsonl\`. Speedup = throughput vs the stage's v0. "coverage" = sum of v0 stage medians / end-to-end v0 total.\n\n`;
  for (const p of PARAMS) {
    const pr = rows.filter((r) => r.param === p); if (!pr.length) continue;
    const st = STAGES[fam(p)];
    const tot = pr.find((r) => r.stage === 'total'), best = pr.find((r) => r.stage === 'total_best');
    const sum = st.reduce((a, s) => a + (pr.find((r) => r.stage === s && r.variant === `${s}.v0`)?.wall_ns_median ?? 0), 0);
    md += `### ${p}\n\nend-to-end v0 stages: ${t(tot?.wall_ns_median)}, best assembled: ${t(best?.wall_ns_median)} (${x(tot && best ? tot.wall_ns_median / best.wall_ns_median : null)}), coverage ${tot ? (100 * sum / tot.wall_ns_median).toFixed(0) + '%' : '—'}\n\n`;
    md += '| stage | variant | median | CPU/op | threads | share of v0 total | speedup | match |\n|---|---|---|---|---|---|---|---|\n';
    for (const s of st) {
      const v0 = pr.find((r) => r.stage === s && r.variant === `${s}.v0`);
      for (const r of pr.filter((r) => r.stage === s).sort((a, c) => a.variant.localeCompare(c.variant)))
        md += `| ${s} | \`${r.variant}\` ${r.variant_name} | ${t(r.wall_ns_median)} | ${t(r.cpu_ns_per_op)} | ${r.threads ?? 1} | ${r.variant === `${s}.v0` && tot ? (100 * r.wall_ns_median / tot.wall_ns_median).toFixed(1) + '%' : ''} | ${x(v0 ? eff(v0) / eff(r) : null)} | ${r.match ? '✓' : '✗'} |\n`;
    }
    md += '\n';
  }
  writeAfterMarker(`docs/${l}/verify-stages.md`, md, `${l}: verify stages`);
}

// ---------- per-lib memory docs
for (const [l, rows] of Object.entries(M)) {
  let md = `## Results\n\nGenerated from \`results/${l}/memory.jsonl\`. Method: ${[...new Set(rows.map((r) => r.stack_method))].join('; ')}.\n\n`;
  for (const op of ['keygen', 'sign', 'verify', 'verify-stage']) {
    const or = rows.filter((r) => r.op === op); if (!or.length) continue;
    const vs = [...new Set(or.map((r) => r.stage ? `${r.variant}` : r.variant))].sort();
    md += `### ${op}: peak stack\n\n| param | ${vs.map((v) => `\`${v}\``).join(' | ')} |\n|---|${vs.map(() => '---').join('|')}|\n`;
    for (const p of PARAMS) { if (!or.some((r) => r.param === p)) continue;
      md += `| ${p} | ${vs.map((v) => b(or.find((r) => r.param === p && r.variant === v)?.stack_bytes)).join(' | ')} |\n`; }
    md += `\n### ${op}: heap allocated per op\n\n| param | ${vs.map((v) => `\`${v}\``).join(' | ')} |\n|---|${vs.map(() => '---').join('|')}|\n`;
    for (const p of PARAMS) { if (!or.some((r) => r.param === p)) continue;
      md += `| ${p} | ${vs.map((v) => b(or.find((r) => r.param === p && r.variant === v)?.heap_alloc_bytes_per_op)).join(' | ')} |\n`; }
    md += '\n';
  }
  writeAfterMarker(`docs/${l}/memory.md`, md, `${l}: memory`);
}

// ---------- cross-library sections in RESULTS.md
const libs = Object.keys(S);
let md = '\n## Verify split into stages\n\nEach stage timed in isolation with the library\'s own internals (v0) and its alternatives; canonical intermediate outputs are byte-compared across libraries (`results/MATCH.md`). Cells: v0 median → fastest correct single-threaded alternative (variant).\n\n';
const bestStage = {};
for (const [f, st] of Object.entries(STAGES)) for (const s of st) {
  md += `### ${f} / ${s}\n\n| param | ${libs.join(' | ')} | best overall |\n|---|${libs.map(() => '---').join('|')}|---|\n`;
  for (const p of PARAMS.filter((p) => fam(p) === f)) {
    let gbest = null;
    const cells = libs.map((l) => {
      const rs = S[l].filter((r) => r.param === p && r.stage === s && r.match);
      if (!rs.length) return '—';
      const v0 = rs.find((r) => r.variant === `${s}.v0`);
      const st1 = rs.filter((r) => (r.threads ?? 1) === 1);
      const best = st1.reduce((a, c) => (c.wall_ns_median < a.wall_ns_median ? c : a), st1[0]);
      if (!gbest || best.wall_ns_median < gbest.r.wall_ns_median) gbest = { l, r: best };
      return `${t(v0?.wall_ns_median)} → ${t(best.wall_ns_median)} (${best.variant.split('.')[1]})`;
    });
    if (gbest) (bestStage[p] ??= {})[s] = gbest;
    md += `| ${p} | ${cells.join(' | ')} | ${gbest ? `**${gbest.l} ${gbest.r.variant}** ${t(gbest.r.wall_ns_median)}` : '—'} |\n`;
  }
  md += '\n';
}
md += '### Best possible verify: stage-wise best of all libraries vs best real implementations\n\n"best-of-breed" sums the fastest correct implementation of every stage across all libraries (a lower bound if one implementation combined them all). It is compared with the fastest assembled pipeline per library (`total_best`) and the fastest end-to-end verify variant from the main benchmark.\n\n';
md += '| param | best-of-breed (sum of stage minima) | stage winners | best `total_best` (lib) | best end-to-end verify variant (lib) |\n|---|---|---|---|---|\n';
for (const p of PARAMS) {
  const bs = bestStage[p]; if (!bs) continue;
  const sum = Object.values(bs).reduce((a, g) => a + g.r.wall_ns_median, 0);
  const tb = libs.flatMap((l) => S[l].filter((r) => r.param === p && r.stage === 'total_best' && r.match).map((r) => ({ l, r })));
  const tbb = tb.reduce((a, c) => (!a || c.r.wall_ns_median < a.r.wall_ns_median ? c : a), null);
  const ve = Object.entries(B).flatMap(([l, rows]) => rows.filter((r) => r.op === 'verify' && r.param === p && r.match && r.threads === 1).map((r) => ({ l, r })));
  const veb = ve.reduce((a, c) => (!a || c.r.wall_ns_median < a.r.wall_ns_median ? c : a), null);
  md += `| ${p} | ${t(sum)} | ${Object.entries(bs).map(([s, g]) => `${s}: ${g.l}`).join(', ')} | ${tbb ? `${t(tbb.r.wall_ns_median)} (${tbb.l})` : '—'} | ${veb ? `${t(veb.r.wall_ns_median)} (${veb.l} ${veb.r.variant})` : '—'} |\n`;
}

const mlibs = Object.keys(M);
md += '\n## Memory: peak stack per operation\n\nv0 = baseline variant; "min" = smallest stack among that process\'s variants (single-threaded or per worker). Methods differ by runtime (see each `docs/<lib>/memory.md`), so compare within a language more than across.\n\n';
for (const op of ['keygen', 'sign', 'verify']) {
  md += `### ${op}\n\n| param | ${mlibs.map((l) => `${l} v0 / min`).join(' | ')} |\n|---|${mlibs.map(() => '---').join('|')}|\n`;
  for (const p of PARAMS) { if (!mlibs.some((l) => M[l].some((r) => r.param === p && r.op === op))) continue;
    md += `| ${p} | ${mlibs.map((l) => { const rs = M[l].filter((r) => r.param === p && r.op === op && r.stack_bytes != null); if (!rs.length) return '—';
      const v0 = rs.find((r) => r.variant === `${op}.v0`); const mn = rs.reduce((a, c) => (c.stack_bytes < a.stack_bytes ? c : a));
      return `${b(v0?.stack_bytes)} / ${b(mn.stack_bytes)}${mn.variant !== v0?.variant ? ` (${mn.variant.split('.')[1]})` : ''}`; }).join(' | ')} |\n`; }
  md += `\n${op}, heap allocated per op (v0):\n\n| param | ${mlibs.join(' | ')} |\n|---|${mlibs.map(() => '---').join('|')}|\n`;
  for (const p of PARAMS) { if (!mlibs.some((l) => M[l].some((r) => r.param === p && r.op === op))) continue;
    md += `| ${p} | ${mlibs.map((l) => b(M[l].find((r) => r.param === p && r.variant === `${op}.v0`)?.heap_alloc_bytes_per_op)).join(' | ')} |\n`; }
  md += '\n';
}
appendFileSync(new URL('RESULTS.md', root), md);
writeFileSync(new URL('results/summary-phase2.json', root), JSON.stringify({ stages: S, memory: M }));
console.log('phase 2 report written for', libs.join(','), '/', mlibs.join(','));
